#include "libft.h"

char	*ft_strdup(char *s)
{
	int			i;
	char		*dest;
	size_t		src_len;

	src_len = ft_strlen(s);
	dest = malloc(sizeof(char) * (src_len + 1));
	i = 0;
	if (!dest)
		return (NULL);
	while (s[i] != '\0')
	{
		dest[i] = s[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
